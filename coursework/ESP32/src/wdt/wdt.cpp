#include "wdt.h"
#include <soc/timer_group_struct.h>
#include <soc/timer_group_reg.h>

// ═══════════════════════════════════════════════════════════════════
//                    ДЛЯ ДОПИТЛИВИХ
//         Чому Deep Sleep у Wokwi не працює без цього файлу
// ═══════════════════════════════════════════════════════════════════
//
// ── СИМПТОМ ──
//
// Пристрій друкує «Засинаємо на 60 с» — і замість тиші на хвилину
// миттєво перезавантажується:
//
//     rst:0x8 (TG1WDT_SYS_RESET)
//     причина ресету 5, bootCount знову 1
//
// Виглядає як баг у власному коді. Це не він.
//
//
// ── ЩО НАСПРАВДІ ВІДБУВАЄТЬСЯ ──
//
// Ось кінець esp_deep_sleep_start() в ESP-IDF 4.4:
//
//     portENTER_CRITICAL(&spinlock_rtc_deep_sleep);  // переривання ВИМКНЕНІ
//     esp_sleep_start(...);                          // тут чіп має згаснути
//     while (1) { ; }                                // страховка на кілька тактів
//
// На залізі RTC знімає живлення за мікросекунди, і до while(1) справа
// доходить хіба на пару тактів. Симулятор же просто зупиняє ЦП —
// а таймери групи при цьому продовжують рахувати. Спливає таймаут
// watchdog — і замість пробудження ви отримуєте ресет.
//
//
// ── ЧОМУ WATCHDOG ДВА ──
//
// У ESP32 дві однакові групи таймерів, і в кожній свій watchdog:
//
//     TG0 → Task Watchdog       стежить, щоб задачі віддавали час IDLE
//     TG1 → Interrupt Watchdog  стежить, щоб переривання не глушили надовго
//
// Потрібні обидва, і це виміряно покроково — глушимо по одному й
// дивимось, скільки проживе сон:
//
//     нічого не чіпаємо   ~0.3 с   TG1WDT_SYS_RESET  (rst:0x8, причина 5)
//     заглушили TG1       ~15 с    TG0WDT_SYS_RESET  (rst:0x7, причина 6)
//     заглушили обидва    60 с     DEEPSLEEP_RESET   (rst:0x5, причина 8)
//
// Третій watchdog, RTC, нас не зачепив: у цій конфігурації bootloader
// вимикає його ще до старту застосунку. Якщо колись побачите
// RTCWDT_SYS_RESET (rst:0x9) — його глушать інакше, через регістри
// RTC_CNTL_WDTCONFIG0_REG, а не через групи таймерів.
//
//
// ── ЧОМУ РОЗТЯГУЄМО ТАЙМАУТ, А НЕ ВИМИКАЄМО ──
//
// Очевидний хід — вимкнути:
//
//     tg->wdt_config0.en = 0;
//
// Це рівно те, що робить сам IDF у mwdt_ll_disable(). І в Wokwi воно
// не дає нічого: біт en симулятор ігнорує, ресет прилітає як раніше.
// Перевірено.
//
// А от регістри таймауту він поважає. Нам байдуже, як саме watchdog
// замовкне — вимкненим чи таким, що не спрацює за все життя пристрою.
// Тому виставляємо максимум.
//
//
// ── ЯК ЦЕ РАХУЄТЬСЯ ──
//
// Такт watchdog = 12.5 нс × clk_prescale (це APB 80 МГц, поділений
// на прескалер). Максимум прескалера 0xFFFF дає такт ~819 мкс.
// Максимальний таймаут стадії 0xFFFFFFFF таких тактів — це понад
// місяць. Для хвилини сну із запасом у сорок тисяч разів.
//
//
// ── ДВІ СТАДІЇ, І ВАЖЛИВІ ОБИДВІ ──
//
// Watchdog в ESP32 багатостадійний. IDF налаштовує його так:
//
//     стадія 0 (wdt_config2) → переривання, тобто друк паніки в Serial
//     стадія 1 (wdt_config3) → системний ресет
//
// Розтягнути тільки нульову — ресет усе одно прилетить, просто від
// наступної стадії. Саме на цьому легко зупинитись і вирішити, що
// «спосіб не працює».
//
//
// ── ЗАХИСТ ЗАПИСУ ──
//
// Регістри watchdog замкнені: поки в wdt_wprotect не лежить ключ
// TIMG_WDT_WKEY_VALUE (0x50D83AA1), запис у решту регістрів групи
// мовчки ігнорується. Помилки не буде — просто нічого не станеться.
// Тому пишемо ключ на початку і повертаємо захист у кінці.
//
//
// ── ПЕРЕНОСИМІСТЬ ──
//
// Код саме для КЛАСИЧНОГО ESP32. У S3/C3/C6 та сама логіка, але інші
// імена полів: замість wdt_wprotect там wdtwprotect.wdt_wkey і так
// далі — дивіться hal/<чіп>/include/hal/mwdt_ll.h у своєму фреймворку.
//
// І головне: на реальній платі цей виклик не потрібен. Він нешкідливий
// (RTC гасить домен разом із таймерами за мікросекунди), але потрібен
// він саме симулятору.
// ═══════════════════════════════════════════════════════════════════

// Одна група: найповільніший такт + максимальні таймаути обох стадій.
static void stretch(timg_dev_t* tg) {
    tg->wdt_wprotect             = TIMG_WDT_WKEY_VALUE;  // ключ: знімаємо захист
    tg->wdt_config1.clk_prescale = 0xFFFF;               // такт ~819 мкс
    tg->wdt_config2              = 0xFFFFFFFF;           // стадія 0 — переривання
    tg->wdt_config3              = 0xFFFFFFFF;           // стадія 1 — ресет системи
    tg->wdt_feed                 = 1;                    // відлік з нуля
    tg->wdt_wprotect             = 0;                    // повертаємо захист
}

void wdt_silence_for_sleep() {
    stretch(&TIMERG0);   // task watchdog
    stretch(&TIMERG1);   // interrupt watchdog
}
